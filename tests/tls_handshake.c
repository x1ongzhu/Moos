/*
 * Host diagnostic for the portable TLS profile.
 * It performs no HTTP request and uses no API key.
 *
 * Usage: tls_handshake [connect-host] [port] [certificate-host] [unix-time]
 */
#include "../tls/core_abi.h"
#include <sys/socket.h>
#include <sys/time.h>
#include <netdb.h>
#include <fcntl.h>
#include <unistd.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

extern MTWord MossTLSCore(MTWord,void *,void *);
static MTValidationCache validationCache;
static unsigned lastWarmup;
static MTWord lastX509;
static unsigned lastInsecure;

static int readSeed(unsigned char seed[32]) {
 int fd=open("/dev/urandom",O_RDONLY);
 size_t done=0;
 ssize_t n;
 if(fd<0) return 0;
 while(done<32) {
  n=read(fd,seed+done,32-done);
  if(n<=0) { close(fd); return 0; }
  done+=(size_t)n;
 }
 close(fd);
 return 1;
}

int main(int argc,char **argv) {
 struct addrinfo hints,*ai; struct timeval tv={20,0}; MTInit init; MTBuffer b;
 unsigned long flags,n,tx=0,rx=0,epoch; int fd; void *context; size_t size;
 const char *connectHost=argc>1?argv[1]:"api.deepseek.com";
 const char *port=argc>2?argv[2]:"443";
 const char *certHost=argc>3?argv[3]:connectHost;
 if(argc>5) {
  fprintf(stderr,"Usage: %s [connect-host] [port] [certificate-host] [unix-time]\n",argv[0]);
  return 2;
 }
 memset(&hints,0,sizeof(hints)); hints.ai_family=AF_INET; hints.ai_socktype=SOCK_STREAM;
 if(getaddrinfo(connectHost,port,&hints,&ai)) { perror("getaddrinfo"); return 2; }
 fd=socket(ai->ai_family,ai->ai_socktype,0);
 if(fd<0 || connect(fd,ai->ai_addr,ai->ai_addrlen)) {
  perror("connect"); if(fd>=0) close(fd); freeaddrinfo(ai); return 3;
 }
 freeaddrinfo(ai);
 setsockopt(fd,SOL_SOCKET,SO_RCVTIMEO,&tv,sizeof(tv));
 setsockopt(fd,SOL_SOCKET,SO_SNDTIMEO,&tv,sizeof(tv));
 size=MossTLSCore(MT_SIZE,NULL,NULL);
 context=size?calloc(1,size):NULL;
 if(!context) { close(fd); return 4; }
 memset(&init,0,sizeof(init)); init.host=certHost;
 init.cache=&validationCache;
 if(!readSeed(init.seed)) { close(fd); free(context); return 4; }
 epoch=argc>4?(unsigned long)strtoul(argv[4],NULL,10):(unsigned long)time(NULL);
 init.days=719528UL+epoch/86400UL; init.seconds=epoch%86400UL;
 if(!MossTLSCore(MT_INIT,context,&init)) {
  memset(init.seed,0,sizeof(init.seed)); close(fd); free(context); return 5;
 }
 memset(init.seed,0,sizeof(init.seed));
 for(;;) {
  MossTLSCore(MT_SENDAPP,context,&b);
  if(b.length || b.data) { fputs("Application write allowed before validation\n",stderr); return 9; }
  MossTLSCore(MT_RECVAPP,context,&b);
  if(b.length || b.data) { fputs("Application read allowed before validation\n",stderr); return 9; }
  flags=MossTLSCore(MT_STATE,context,NULL);
  printf("state=%lu sent=%lu received=%lu\n",flags,tx,rx); fflush(stdout);
  if(flags&1) {
   lastX509=MossTLSCore(MT_X509_ERROR,context,NULL);
   MossTLSCore(MT_SENDAPP,context,&b);
   if(b.length || b.data) { fputs("Application write allowed after rejection\n",stderr); return 9; }
   printf("TLS=%lu X509=%lu\n",MossTLSCore(MT_ERROR,context,NULL),MossTLSCore(MT_X509_ERROR,context,NULL));
   close(fd); free(context); return 6;
  }
  if(flags&8) {
   lastWarmup=(flags&32)!=0;
   lastInsecure=(flags&64)!=0;
   if(getenv("MOSS_EXPORT_CACHE") && !strcmp(certHost,"api.deepseek.com")) {
    FILE *out;
    unsigned i;
    if(!validationCache.valid) return 10;
    out=fopen(getenv("MOSS_EXPORT_CACHE"),"w"); if(!out) return 10;
    fputs("/* Generated by scripts/preverify_deepseek.py after full chain validation. */\n#define MOSS_HAS_PREVERIFIED 1\nstatic const MTValidationCache moss_preverified_deepseek = {\n {",out);
    for(i=0;i<32;++i) fprintf(out,"%s0x%02x",i?",":"",validationCache.fingerprint[i]);
    fprintf(out,"},\n 1UL,%luUL,%luUL,%luUL,%luUL\n};\n",
     validationCache.notBeforeDays,validationCache.notBeforeSeconds,
     validationCache.notAfterDays,validationCache.notAfterSeconds);
    if(fclose(out)) return 10;
   }
   printf("%s TLS handshake complete for %s\n",lastInsecure?"Insecure":"Verified",certHost);
   close(fd); free(context); return 0;
  }
  if(flags&2) {
   MossTLSCore(MT_SENDREC,context,&b); n=send(fd,b.data,b.length,0);
   if((long)n<=0) { perror("send"); break; }
   tx+=n; MossTLSCore(MT_SENDREC_ACK,context,&n);
  } else if(flags&4) {
   MossTLSCore(MT_RECVREC,context,&b); n=recv(fd,b.data,b.length,0);
   if((long)n<=0) { perror("recv"); break; }
   rx+=n; MossTLSCore(MT_RECVREC_ACK,context,&n);
  } else {
   printf("TLS=%lu X509=%lu\n",MossTLSCore(MT_ERROR,context,NULL),MossTLSCore(MT_X509_ERROR,context,NULL));
   close(fd); free(context); return 7;
  }
 }
 printf("Incomplete handshake, state=%lu TLS=%lu X509=%lu\n",flags,
  MossTLSCore(MT_ERROR,context,NULL),MossTLSCore(MT_X509_ERROR,context,NULL));
 close(fd); free(context); return 8;
}
